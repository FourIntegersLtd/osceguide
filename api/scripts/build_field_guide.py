"""Regenerate the data-model section of the platform-api field guide.

`docs/guides/platform-api-field-guide.html` (repo root) is a published single page
about this backend. Its `const SCHEMA = [...]` array used to be written by hand and
rotted: a migration landed, `docs/DATA-MODEL.md` changed (it is checked by
`make data-model`), the page did not. Now the array between the two marker comments
is generated, and `--check` fails when it differs from what this script would write.

Routes: the hand-written `API` list is not regenerated, but `--check` fails when it
differs from `openapi.json` by a single method and path.

Sources:
  * groups, slices and table order, the blurbs and the rules: `docs/DATA-MODEL.md`;
  * the columns: `Base.metadata`. A column the document names takes the document's
    type and note; one it does not name gets a type derived from the column.

    python scripts/build_field_guide.py          # rewrite the block in place
    python scripts/build_field_guide.py --check  # exit 1 if the block is stale
"""

from __future__ import annotations

import html
import json
import os
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ.setdefault("APP_ENV", "test")

DOC = ROOT / "docs" / "DATA-MODEL.md"
OPENAPI = ROOT / "openapi.json"
HTTP_METHODS = frozenset({"get", "post", "put", "patch", "delete"})
GUIDE = ROOT.parent / "docs" / "guides" / "platform-api-field-guide.html"

BEGIN = "/* SCHEMA:BEGIN generated by api/scripts/build_field_guide.py */"
END = "/* SCHEMA:END */"
# The hand-written array this script replaced, found once to place the markers.
LEGACY_START = "const SCHEMA = ["
LEGACY_END = "\n// voice owns no tables"

MIXIN_COLUMNS = frozenset({"id", "created_at", "updated_at"})
ADDRESSED_COLUMNS = frozenset({"visibility", "audience_org_id", "audience_group_id"})
FOREIGN_PREFIX = "procrastinate"

# One-line strapline under each group heading; DATA-MODEL.md has none.
GROUP_SUB = {
    "Foundation": "Who you are and who you work for",
    "Content": "The material a candidate is given",
    "The assessment core": "One candidate ran one scenario, however they reached it",
    "Institutions running exams": "A scheduled exam, its circuits, and the people being taught",
    "Access, money and growth": "May this person do this, what it cost, and who sent them",
    "Consumer social features": "Talking to, practising with, and being helped by somebody else",
}
# Not recoverable from the schema: rows nothing updates, and rows rebuilt from a source.
APPEND_ONLY = frozenset(
    {"audit_log", "candidate_result_revisions", "candidate_result_events", "circuit_interventions"}
)
DERIVED = frozenset({"material_chunks"})

TYPE_START = re.compile(
    r"^(uuid|varchar|text|citext|bool|boolean|int|integer|bigint|smallint|timestamptz|"
    r"timestamp|date|time|jsonb|json|numeric|float|double|real|bytea|vector|tsvector|inet)\b"
)
RULE_LABELS = ("UNIQUE", "CHECK", "INDEX", "Domain")


def inline(text: str) -> str:
    """Markdown inline to the page's HTML: code spans become <em>, bold is dropped."""
    text = html.escape(text.replace("\\|", "|"), quote=False)
    text = re.sub(r"`([^`]+)`", r"<em>\1</em>", text)
    return text.replace("**", "").strip()


def plain(text: str) -> str:
    return html.escape(text.replace("\\|", "|").replace("`", "").replace("**", "").strip(), quote=False)


def split_row(line: str) -> list[str]:
    cells = re.split(r"(?<!\\)\|", line.strip().strip("|"))
    return [c.strip() for c in cells]


def names_in(cell: str) -> list[str]:
    """Column names a first cell names, with `x_at/by` expanded."""
    out: list[str] = []
    for span in re.findall(r"`([^`]+)`", cell):
        span = re.sub(r"\b(\w+)_at/by\b", r"\1_at \1_by", span)
        out.extend(re.findall(r"[a-z_][a-z0-9_]*", span))
    return out


class Section:
    def __init__(self, name: str) -> None:
        self.name = name
        self.before: list[str] = []
        self.rows: list[list[str]] = []
        self.after: list[str] = []


def paragraphs(lines: list[str]) -> list[str]:
    out: list[str] = []
    cur: list[str] = []
    for line in lines:
        if not line.strip() or line.strip() == "---":
            if cur:
                out.append(" ".join(cur))
                cur = []
        else:
            cur.append(line.strip())
    if cur:
        out.append(" ".join(cur))
    return out


def parse_doc(markdown: str) -> list[dict[str, Any]]:
    """Groups, each with slices (name, intro lines) and tables (Section), in document order."""
    body = markdown.split("\n## Conventions\n", 1)[1]
    groups: list[dict[str, Any]] = []
    group: dict[str, Any] | None = None
    slice_: dict[str, Any] | None = None
    section: Section | None = None
    state = "intro"
    for line in body.split("\n"):
        if re.match(r"# (?!#)", line):
            name = line[2:].strip()
            if name in ("Voice routing", "Cross-cutting patterns"):
                break
            group = {"g": name, "slices": []}
            groups.append(group)
            slice_ = section = None
            continue
        m = re.match(r"## (\w+) — \d+ tables?$", line)
        if m and group is not None:
            slice_ = {"s": m.group(1), "intro": [], "tables": []}
            group["slices"].append(slice_)
            section = None
            continue
        m = re.match(r"### `([a-z_0-9]+)`$", line)
        if m and slice_ is not None:
            section = Section(m.group(1))
            slice_["tables"].append(section)
            state = "before"
            continue
        if section is None:
            if slice_ is not None:
                slice_["intro"].append(line)
            continue
        if line.startswith("|"):
            cells = split_row(line)
            if cells and cells[0] == "Field":
                state = "rows"
            elif state == "rows" and not set(cells[0]) <= set("-: "):
                section.rows.append(cells)
            continue
        if state == "rows" and line.strip():
            state = "after"
        (section.before if state == "before" else section.after).append(line)
    return groups


def derived_type(column: Any) -> str:
    from sqlalchemy.dialects import postgresql
    from sqlalchemy.exc import CompileError

    try:
        dialect = postgresql.dialect()  # type: ignore[no-untyped-call]
        base = column.type.compile(dialect=dialect).lower().replace("timestamp with time zone", "timestamptz")
    except CompileError:  # custom types (citext) that cannot compile
        base = type(column.type).__name__.lower()
    out = f"{base} {'null' if column.nullable else 'not null'}"
    if column.unique:
        out += " unique"
    for fk in column.foreign_keys:
        rule = (fk.ondelete or "NO ACTION").upper()
        out = f"{out} → {fk.column.table.name}.{fk.column.name} ON DELETE {rule}"
    return out


def field_rows(section: Section, table: Any, addressed: bool) -> list[list[str]]:
    columns = {c.name: c for c in table.columns}
    skip = ADDRESSED_COLUMNS if addressed else frozenset()
    documented: dict[str, tuple[str, str]] = {}
    order: list[str] = []
    for cells in section.rows:
        if len(cells) < 2:
            continue
        names = [n for n in names_in(cells[0]) if n in columns and n not in skip]
        if not names:
            continue
        note = inline(cells[2]) if len(cells) > 2 else ""
        types = [t.strip() for t in re.split(r" / ", cells[1].replace("`", ""))]
        for i, name in enumerate(names):
            if len(types) == len(names):
                raw = types[i]
            elif len(types) == 1 and TYPE_START.match(types[0]):
                raw = types[0]
            else:
                raw = ""
            if not TYPE_START.match(raw):
                prev = documented[order[-1]][0] if order and i > 0 else ""
                raw = prev if raw.lower().startswith("same") else ""
            if name not in documented:
                order.append(name)
            documented[name] = (raw, note)
    rows: list[list[str]] = []
    for name in order:
        raw, note = documented[name]
        rows.append([name, plain(raw) if raw else plain(derived_type(columns[name])), note])
    for name, column in columns.items():
        if name in MIXIN_COLUMNS or name in skip or name in documented:
            continue
        rows.append([name, plain(derived_type(column)), ""])
    return rows


def rules(section: Section) -> list[list[str]]:
    out: list[list[str]] = []
    for para in paragraphs(section.after):
        label = next((k for k in RULE_LABELS if para.startswith(k + " ") or para == k), None)
        if label:
            text = para[len(label) :].strip()
            if text.endswith(".") and text.count(". ") == 0 and "—" not in text:
                text = text[:-1]
            out.append([label.lower(), inline(text)])
        else:
            out.append(["Why", inline(para)])
    return out


def build() -> list[dict[str, Any]]:
    from app.core.db import Base, import_all_models

    import_all_models()
    tables = {t.name: t for t in Base.metadata.sorted_tables if not t.name.startswith(FOREIGN_PREFIX)}
    groups = parse_doc(DOC.read_text(encoding="utf-8"))
    documented = {s.name for g in groups for sl in g["slices"] for s in sl["tables"]}
    if documented != set(tables):
        raise SystemExit(
            f"DATA-MODEL.md and Base.metadata disagree on tables: {sorted(documented ^ set(tables))}"
            " (run `make data-model`)"
        )
    out: list[dict[str, Any]] = []
    for g in groups:
        slices = []
        for sl in g["slices"]:
            intro = paragraphs(sl["intro"])
            entries = []
            for sec in sl["tables"]:
                table = tables[sec.name]
                addressed = {c.name for c in table.columns} >= ADDRESSED_COLUMNS
                flags = []
                if sec.name in APPEND_ONLY:
                    flags.append("append-only")
                if sec.name in DERIVED:
                    flags.append("derived")
                if "updated_at" not in table.columns:
                    flags.append("no updated_at")
                if addressed:
                    flags.append("addressed")
                entry: dict[str, Any] = {"t": sec.name, "b": inline(" ".join(paragraphs(sec.before)))}
                if flags:
                    entry["flags"] = flags
                entry["f"] = field_rows(sec, table, addressed)
                rule_rows = rules(sec)
                if rule_rows:
                    entry["r"] = rule_rows
                entries.append(entry)
            slices.append({"s": sl["s"], "n": inline(intro[0]) if intro else "", "tables": entries})
        out.append({"g": g["g"], "sub": GROUP_SUB.get(g["g"], ""), "slices": slices})
    return out


def j(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(groups: list[dict[str, Any]]) -> str:
    lines = [BEGIN, "const SCHEMA = ["]
    for gi, g in enumerate(groups):
        lines += ["{", f"  g:{j(g['g'])}, sub:{j(g['sub'])},", "  slices:["]
        for si, sl in enumerate(g["slices"]):
            lines.append(f"   {{s:{j(sl['s'])}, n:{j(sl['n'])}, tables:[")
            for ti, t in enumerate(sl["tables"]):
                flags = f", flags:{j(t['flags'])}" if "flags" in t else ""
                lines.append(f"     {{t:{j(t['t'])}, b:{j(t['b'])}{flags}, f:[")
                lines.append(",\n".join(f"       {j(f)}" for f in t["f"]) + "]")
                if "r" in t:
                    lines[-1] += ",\n      r:[" + ",\n         ".join(j(r) for r in t["r"]) + "]"
                lines[-1] += "}" + ("," if ti < len(sl["tables"]) - 1 else "")
            lines.append("   ]}" + ("," if si < len(g["slices"]) - 1 else ""))
        lines += ["  ]", "}" + ("," if gi < len(groups) - 1 else "")]
    lines += ["];", END]
    return "\n".join(lines)


def splice(page: str, block: str) -> str:
    if BEGIN in page and END in page:
        head, rest = page.split(BEGIN, 1)
        return head + block + rest.split(END, 1)[1]
    start = page.index(LEGACY_START)
    end = page.index(LEGACY_END)
    return page[:start] + block + "\n" + page[end:]


def route_drift(page: str) -> list[str]:
    """Routes in openapi.json but not in the guide's `API` list, and the reverse.

    The route rows carry hand-written descriptions and a guard level, so they are
    not regenerated; what is checked is that none is missing or stale.
    """
    block = page.split("const API = [", 1)[1].split("\n];", 1)[0]
    listed = set(re.findall(r'^\s*\["([A-Z]+)","([^"]+)","[A-Z_]+",', block, flags=re.M))
    spec = json.loads(OPENAPI.read_text(encoding="utf-8"))["paths"]
    served = {(m.upper(), p) for p, ops in spec.items() for m in ops if m in HTTP_METHODS}
    missing = [f"missing from the guide: {m} {p}" for m, p in sorted(served - listed, key=lambda x: x[1])]
    stale = [
        f"in the guide, no longer served: {m} {p}" for m, p in sorted(listed - served, key=lambda x: x[1])
    ]
    return missing + stale


def main() -> None:
    page = GUIDE.read_text(encoding="utf-8")
    updated = splice(page, render(build()))
    routes = route_drift(updated)
    if "--check" in sys.argv:
        if updated != page or routes:
            print("docs/guides/platform-api-field-guide.html has drifted.")  # noqa: T201
            if updated != page:
                print("  SCHEMA block is stale. Run scripts/build_field_guide.py")  # noqa: T201
            for line in routes[:20]:
                print(f"  {line}")  # noqa: T201
            if routes:
                print(f"  ({len(routes)} route differences; edit the API list in the guide)")  # noqa: T201
            raise SystemExit(1)
        print("The field guide's SCHEMA block and route list agree with the code.")  # noqa: T201
        return
    for line in routes:
        print(f"route list: {line}")  # noqa: T201
    GUIDE.write_text(updated, encoding="utf-8")
    print(f"Rewrote the SCHEMA block in {GUIDE.name}.")  # noqa: T201


if __name__ == "__main__":
    main()
