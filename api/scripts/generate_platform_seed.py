"""Build `seeds/platform-starter.json` from the captured legacy artefacts.

Run when the fixtures under `tests/fixtures/` change; the output is committed,
so a deployment seeds from a file rather than from the test tree.

    python scripts/generate_platform_seed.py

The domain and competency ids come from the legacy feedback models, because
those are the ids years of stored results are keyed by and the ids a migrated
result carries. Where two domains in one exam used the same competency name —
legal in the legacy models, which nested them per domain, and refused by
`rubrics.parse_structure`, which requires them unique across the rubric — the
clashing one is qualified with its domain and the original is recorded in
`legacy_id` so the mapping is not lost.
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SCHEMAS = ROOT / "tests/fixtures/legacy_schemas/b2c"
PROMPTS = ROOT / "tests/fixtures/legacy_prompts"
# Marking prompts written for this platform, for exams legacy never had one for.
AUTHORED_PROMPTS = ROOT / "seeds/prompts"
OUT = ROOT / "seeds/platform-starter.json"

# Persistence keys on the legacy models, not anything anyone is marked on.
META = {
    "attempt_id",
    "created_at",
    "evaluated_by",
    "feedback_id",
    "mock_id",
    "station_id",
    "updated_at",
    "user_id",
    "live_coverage",
    "station_type",
}
# Carried as narrative rather than scored. `b2b` excludes exactly these three
# from its scoring domains too.
NARRATIVE = {"actionable_feedback", "clinical_analysis", "overall_priorities"}
# A legacy field repeated inside every domain as a catch-all; not a competency.
NOT_A_COMPETENCY = {"generic_domains"}

EXAMS: dict[str, tuple[str, int, int]] = {
    "sca": ("Simulated Consultation Assessment", 120, 720),
    "plab": ("PLAB 2", 90, 480),
    "casc": ("CASC", 60, 420),
    "ortho": ("Orthopaedic interview", 120, 600),
}
# b2c's pacing marks, which the engine renders phase budgets from.
PACING: dict[str, tuple[int, int, int, int]] = {
    "sca": (720, 360, 30, 120),
    "plab": (480, 240, 30, 90),
    "casc": (420, 210, 30, 90),
    "ortho": (600, 300, 30, 120),
}


def humanise(key: str) -> str:
    return key.replace("_", " ").capitalize()


def resolve(spec: dict[str, Any], defs: dict[str, Any]) -> dict[str, Any] | None:
    """A property's target, through `$ref`, `allOf`, or a nullable `anyOf`."""
    for candidate in [spec, *(spec.get("allOf") or []), *(spec.get("anyOf") or [])]:
        ref = candidate.get("$ref")
        if ref:
            return defs.get(ref.split("/")[-1])
    return None


def structure_for(code: str) -> dict[str, Any]:
    raw = json.loads((SCHEMAS / f"{code}.json").read_text())
    defs = raw.get("$defs", {})

    scored: list[tuple[str, list[str]]] = []
    sections: list[dict[str, str]] = []
    for name, spec in raw["properties"].items():
        if name in META:
            continue
        if name in NARRATIVE:
            sections.append({"id": name, "label": humanise(name), "kind": "list"})
            continue
        target = resolve(spec, defs)
        competencies = [c for c in (target or {}).get("properties", {}) if c not in NOT_A_COMPETENCY]
        scored.append((name, competencies))

    seen = Counter(c for _, competencies in scored for c in competencies)
    domains = []
    for name, competencies in scored:
        entries = []
        for competency in competencies:
            clashes = seen[competency] > 1
            entry: dict[str, Any] = {
                "id": f"{name}_{competency}" if clashes else competency,
                "label": humanise(competency),
                # Empty on purpose: the marking wording lives in the system
                # prompt today, and has to be authored per competency by a
                # human before per-competency feedback means anything.
                "descriptors": {},
            }
            if clashes:
                entry["legacy_id"] = competency
            entries.append(entry)
        domains.append(
            {
                "id": name,
                "label": humanise(name),
                # Nothing starts live: the legacy behaviour marked everything
                # after the consultation, and turning that on is a decision.
                "live": False,
                "competencies": entries,
            }
        )

    if not sections:
        sections.append({"id": "actionable_feedback", "label": "Actionable feedback", "kind": "list"})
    return {"scale": ["R", "A", "G"], "domains": domains, "sections": sections}


def build() -> dict[str, Any]:
    out: dict[str, Any] = {
        "_comment": (
            "Generated by scripts/generate_platform_seed.py from the legacy feedback "
            "schemas and marking prompts captured in platform-api/tests/fixtures/. Do "
            "not hand-edit: regenerate. Domain and competency ids are the legacy ones "
            "so a migrated result stays comparable with one marked next week."
        ),
        "exams": [],
    }
    for code, (name, reading, simulation) in EXAMS.items():
        # An authored prompt wins over the captured legacy one. No fallback: an
        # exam with no prompt of its own is refused here rather than marked with
        # another exam's (CASC was marked with the RCGP GP prompt for years).
        authored_prompt = AUTHORED_PROMPTS / f"{code}_system.txt"
        source = authored_prompt if authored_prompt.exists() else PROMPTS / f"b2c_{code}_system.txt"
        total, history, intro, safety = PACING[code]
        rubric: dict[str, Any] = {
            "title": f"{name} marking rubric",
            "structure": structure_for(code),
            "system_prompt": source.read_text(),
            "pacing": {
                "total_seconds": total,
                "history_seconds": history,
                "introduction_seconds": intro,
                "safety_net_seconds": safety,
            },
            "prompt_source": source.name,
        }
        out["exams"].append(
            {
                "code": code,
                "name": name,
                "default_reading_seconds": reading,
                "default_simulation_seconds": simulation,
                "station_attempt_limit": 3,
                "rubric": rubric,
            }
        )
    return out


def main() -> int:
    data = build()
    OUT.write_text(json.dumps(data, indent=2) + "\n")
    for exam in data["exams"]:
        domains = exam["rubric"]["structure"]["domains"]
        competencies = sum(len(d["competencies"]) for d in domains)
        qualified = sum(1 for d in domains for c in d["competencies"] if "legacy_id" in c)
        print(  # noqa: T201
            f"{exam['code']:6} {len(domains)} domains, {competencies} competencies"
            f"{f' ({qualified} disambiguated)' if qualified else ''}"
            f", prompt {exam['rubric']['prompt_source']}"
        )
    print(f"wrote {OUT.relative_to(ROOT)}")  # noqa: T201
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
