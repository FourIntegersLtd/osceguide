def _spec() -> dict:
    return json.loads((ROOT / "openapi.json").read_text(encoding="utf-8"))


def _operations(spec: dict) -> set[str]:
    return {
        f"{method.upper()} {path}"
        for path, item in spec["paths"].items()
        for method in item
        if method in ("get", "post", "put", "patch", "delete")
    }


def _lines(path: Path) -> int:
    return len(path.read_text(encoding="utf-8").splitlines())


def report() -> str:
    from tests.guards.test_domain_rules_are_reachable import KNOWN_UNWIRED, unreachable_rules

    spec = _spec()
    present = _operations(spec)
    missing = [p for p in PLANNED if p not in present]
    dead = set(unreachable_rules())

    out: list[str] = [MARKER, ""]
    out.append("_Generated by `scripts/status_report.py`. Do not edit below the marker; run `make status`._")
    out.append("")
    ops = len(present)
    out.append(
        f"**{ops} operations across {len(spec['paths'])} paths. "
        f"{len([d for d in FEATURES.iterdir() if d.is_dir() and not d.name.startswith('_')])} slices. "
        f"{len(list((ROOT / 'alembic' / 'versions').glob('*.py')))} migrations.**"
    )
    out.append("")

    out.append("## Slices")
    out.append("")
    out.append("| Slice | App lines | Domain rules | Unwired | Routes |")
    out.append("|---|---|---|---|---|")
    for slice_dir in sorted(p for p in FEATURES.iterdir() if p.is_dir() and not p.name.startswith("_")):
        name = slice_dir.name
        app_lines = sum(_lines(f) for f in slice_dir.glob("*.py"))
        unwired = sorted(rule for (s, rule) in dead if s == name)
        import ast

        rules = sum(
            1
            for domain_file in slice_dir.glob("domain*.py")
            for n in ast.parse(domain_file.read_text(encoding="utf-8")).body
            if isinstance(n, ast.FunctionDef | ast.AsyncFunctionDef) and not n.name.startswith("_")
        )
        routes = sum(1 for op in present if f"/{name.replace('_', '-')}" in op or f"/{name}" in op)
        flag = ", ".join(unwired) if unwired else "—"
        out.append(f"| `{name}` | {app_lines} | {rules} | {flag} | {routes} |")
    out.append("")

    out.append("## Planned endpoints that do not exist")
    out.append("")
    if missing:
        for path in missing:
            out.append(f"- `{path}`")
    else:
        out.append("None.")
    out.append("")

    out.append("## Domain rules with no production caller")
    out.append("")
    out.append("Each is listed in `tests/guards/test_domain_rules_are_reachable.py` with a reason.")
    out.append("The guard fails if this list grows, and fails if an entry becomes reachable and is")
    out.append("left here.")
    out.append("")
    for slice_name, rule in sorted(dead):
        out.append(f"- `{slice_name}.{rule}` — {KNOWN_UNWIRED.get((slice_name, rule), 'undocumented')}")
    out.append("")
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit non-zero if STATUS.md is stale")
    parser.add_argument("--write", action="store_true", help="rewrite the generated half of STATUS.md")
    args = parser.parse_args()

    generated = report()
    current = STATUS.read_text(encoding="utf-8") if STATUS.exists() else ""
    prose = current.split(MARKER)[0].rstrip() if MARKER in current else current.rstrip()

    if args.write:
        STATUS.write_text(f"{prose}\n\n{generated}", encoding="utf-8")
        print(f"wrote {STATUS}")  # noqa: T201
        return

    if args.check:
        expected = f"{prose}\n\n{generated}"
        if current != expected:
            print("STATUS.md is stale; run `python scripts/status_report.py --write`.")  # noqa: T201
            raise SystemExit(1)
        print("STATUS.md agrees with the code.")  # noqa: T201
        return

    print(generated)  # noqa: T201


if __name__ == "__main__":
    main()
