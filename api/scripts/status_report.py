"""Derive the project's status from the code, rather than from memory.

A hand-written status document drifted badly: slices were described as
complete while their rules had no caller and their routes did not exist. This
reads the truth back out — which domain rules are reachable, which planned
endpoints are present, how big each slice is — so the document cannot claim
more than the code does.

    python scripts/status_report.py            # print the report
    python scripts/status_report.py --check    # non-zero if STATUS.md is stale
"""

