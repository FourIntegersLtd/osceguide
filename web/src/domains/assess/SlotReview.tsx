/**
 * A station, marked three ways.
 *
 * An observer's own review, the lead's authoritative one, and what everybody
 * who watched agreed — beside the machine's marking. The retiring client had
 * the first of those and the platform had no screen for the other two at all,
 * so a GP lead's review existed on the backend and nothing could write one.
 *
 * The fields to rate are the slot's review form (`SlotReviewsRead.form`),
 * generated by the backend from the station's rubric: every rateable path,
 * the rating kind they take and the domains a submit must cover. So the form
 * is the same for every exam and holds no list of domains or grades here.
 * The backend refuses a submit that leaves a required domain unrated, so that
 * rule is shown, not enforced, in the browser.
 */
/** `attempt_failed_reason` is declared here until the generated types carry it. */
type SlotReviewsRead = SlotReviews & { attempt_failed_reason?: string | null };

export function SlotReview({
  orgSlug,
  slotId,
  attemptId,
  sittingId = null,
}: {
  orgSlug: string;
  slotId: string;
  attemptId: string | null;
  /** The sitting this was opened from, when it was opened from its results. */
  sittingId?: string | null;
}) {
  const w = useAssessWords();
  /*
   * My review is read directly (`GET .../reviews/mine`). An earlier version
   * called that route before it existed, answered 405 on every load and
   * swallowed it, so a reviewer's own draft never came back; a failure here
   * is a failure, not "no review".
   */

  const state = useAsync(
    async (signal) => {
      const [marking, reviews, mine] = await Promise.all([
        // No marking yet (a 404) is an ordinary state beside a review form, and so is a marking
        // this person may not read (a 403). Any other failure is a failure: the boundary shows it.
        readMarking(attemptId, signal),
        readSlotReviews(orgSlug, slotId, signal) as Promise<SlotReviewsRead>,
        readMySlotReview(orgSlug, slotId, signal),
      ]);
      return { feedback: marking.feedback, hidden: marking.hidden, reviews, mine };
    },
    [orgSlug, slotId, attemptId],
  );

  const { hrefFor } = useSurface();
  // The sitting's report names the circuit and candidate and gives the neighbours to step to; it is a convenience, so a failure says so beside the form.
  const report = useAsync(
    (signal) => (sittingId ? readSittingReport(orgSlug, sittingId, signal) : Promise.resolve(null)),
    [orgSlug, sittingId],
  );
  const candidates = report.data?.candidates ?? [];
  const steps = candidateSteps(candidates, slotId);
  const context = slotContext(candidates, slotId);
  return (
    <section aria-label="Mark this station" className={b2bTokens.assessPage}>
      {sittingId && context ? (
        <div>
          <Link href={hrefFor(`/sittings/${sittingId}/results`)} className="text-assess-label text-osce-accent">
            ‹ {context.back}
          </Link>
        </div>
      ) : null}
      <div className="flex flex-wrap items-end justify-between gap-4">
        <div>
          {context ? <div className={b2bTokens.assessEyebrow}>{context.eyebrow}</div> : null}
          <h1 className={b2bTokens.assessTitle}>Mark this station</h1>
          <p className={b2bTokens.assessDesc}>The automatic marking, your marks and the admin&apos;s review.</p>
        </div>
        {sittingId && steps ? <CandidateStepper steps={steps} sittingId={sittingId} /> : null}
        {report.error ? <p className="text-assess-meta text-osce-ink-500">Could not load the other candidates.</p> : null}
      </div>
      {state.data?.hidden ? (
        <div className={boardPad}>
          <h2 className="text-base font-semibold leading-[1.2]">{`Not your ${w.circuit}`}</h2>
          <div role="alert" className={boardAlert("warn")}>
            {`You are not named on this station's ${w.circuit}, so its marking is hidden from you.`}
          </div>
        </div>
      ) : null}
      <AsyncBoundary state={state}>
        {(data) => (
          <Editor
            orgSlug={orgSlug}
            slotId={slotId}
            attemptId={attemptId}
            feedback={data.feedback}
            reviews={data.reviews}
            initial={data.mine}
            onSaved={state.reload}
          />
        )}
      </AsyncBoundary>
    </section>
  );
}

function Editor({
  orgSlug,
  slotId,
  attemptId,
  feedback,
  reviews,
  initial,
  onSaved,
}: {
  orgSlug: string;
  slotId: string;
  attemptId: string | null;
  feedback: AttemptFeedbackRead | null;
  reviews: SlotReviewsRead;
  initial: { id: string; field_values: Record<string, unknown>; notes: string | null; status: string } | null;
  onSaved: () => void;
}) {
  const w = useAssessWords();
  const { session } = useSession();
  const isAdmin = can(session, "sign_off_results");
  const open = openForm(isAdmin);
  // The admin's review status is read by its own form; the steps only follow it.
  const [adminStatus, setAdminStatus] = useState<string | null>(null);
  const form = reviews.form ?? null;
  // Results arrive oldest first; the latest marking is the one to agree or disagree with.
  const result = feedback?.results?.at(-1) ?? null;
  const payload = result?.payload ?? null;

  /*
   * Keyed by the form's own paths (`tasks.safety_net.score`). The backend
   * counts only a path that ends in the rubric's rating field, and a bare
   * domain key would write a rating that scores, summaries and completion
   * checks all silently ignore — so the path is never built here.
   */
  const [ratings, setRatings] = useState<Record<string, RatingValue>>(() =>
    initialRatings(form, initial?.field_values),
  );
  const [notes, setNotes] = useState(initial?.notes ?? "");
  const [busy, setBusy] = useState<"draft" | "completed" | "retry" | "withdraw" | null>(null);
  const [error, setError] = useState<Error | null>(null);
  const [saved, setSaved] = useState<string | null>(null);
  // Its own message, shown beside the marking it belongs to and not under the marks form too.
  const [retryError, setRetryError] = useState<Error | null>(null);

  const submitted = initial?.status === "completed";
  const marking = markingState({
    attemptId,
    hasResult: result !== null,
    hasRubric: Boolean(feedback?.rubric),
    markingFailed: feedback?.marking_failed === true,
    failedReason: reviews.attempt_failed_reason,
  });
  // The AI mark arrives on the attempt's own events: the page follows it rather than asking again.
  useMeEvents(
    marking === "pending" ? ["attempt"] : null,
    useCallback(
      (event) => {
        if (event.name === "resync" || event.data.attempt_id === attemptId) onSaved();
      },
      [attemptId, onSaved],
    ),
  );
  const retryMarking = useCallback(async () => {
    setBusy("retry");
    setRetryError(null);
    try {
      await retrySlotMarking(orgSlug, slotId);
      onSaved();
    } catch (cause) {
      setRetryError(cause instanceof Error ? cause : new Error(String(cause)));
    } finally {
      setBusy(null);
    }
  }, [orgSlug, slotId, onSaved]);
  const steps = slotReviewSteps({
    marking,
    mine: initial?.status === "completed" ? "completed" : initial ? "draft" : "none",
    admin: !isAdmin ? null : adminStatus === "completed" ? "completed" : adminStatus ? "draft" : "none",
  });

  const persist = useCallback(
    async (status: "draft" | "completed") => {
      setBusy(status);
      setError(null);
      try {
        await saveReview(orgSlug, slotId, { fieldValues: fieldValuesFor(ratings), notes: notes || null, status });
        setSaved(status === "draft" ? "Draft saved" : "Review submitted");
        onSaved();
      } catch (cause) {
        setError(cause instanceof Error ? cause : new Error(String(cause)));
      } finally {
        setBusy(null);
      }
    },
    [orgSlug, slotId, ratings, notes, onSaved],
  );

  const withdraw = useCallback(async () => {
    if (!initial) return;
    setBusy("withdraw");
    setError(null);
    try {
      await withdrawReview(orgSlug, slotId, initial.id);
      onSaved();
    } catch (cause) {
      setError(cause instanceof Error ? cause : new Error(String(cause)));
    } finally {
      setBusy(null);
    }
  }, [orgSlug, slotId, initial, onSaved]);

  const mineReadOnly = submitted;
  const nowId = open;
  return (
    <>
      <div className={reviewCard}>
        <div className="flex flex-wrap gap-2">
          {steps.map((step) => (
            <div key={step.id} className={boardRailStep(step.state, step.id === nowId)}>
              <b className="block text-assess-label font-medium">{step.label}</b>
              {step.note}
            </div>
          ))}
        </div>
        <div className="text-assess-label">{slotNextLine(open, steps)}</div>
      </div>
      <div className="flex flex-wrap items-start gap-6">
        <div className="flex min-w-0 flex-[999_1_520px] flex-col gap-6">
          {/* One form per page: an admin writes the review that counts, anyone else their own marks. */}
          {open === "mine" ? (
            <div className={reviewCard}>
              <div className="flex justify-between gap-3">
                <h2 className="text-base font-semibold leading-normal">Your marks</h2>
                <span className={boardChip(submitted ? "ok" : "neutral")}>{submitted ? "Submitted" : "Draft"}</span>
              </div>
              {error && <div role="alert" className={boardAlert("bad")}>{assessErrorMessage(error, w)}</div>}
              {saved && !error && <div role="status" className={boardAlert("ok")}>{saved}</div>}

              <ReviewFields
                form={form}
                ratings={ratings}
                onRate={(path, value) => setRatings((current) => ({ ...current, [path]: value }))}
                payload={payload}
                disabled={mineReadOnly}
              />

              <label className="block">
                <span className={`${boardLabel} !mb-2`}>Notes</span>
                <textarea
                  rows={5}
                  value={notes}
                  disabled={mineReadOnly}
                  onChange={(event) => setNotes(event.target.value)}
                  className={`${boardInput} min-h-24 py-2.5 disabled:bg-canvas`}
                  placeholder="What you saw, in the words you would say to them."
                />
              </label>

              {!mineReadOnly && (
                <div className="mt-2 flex flex-wrap items-center gap-2.5 border-t border-osce-border-light pt-6">
                  {initial ? (
                    <button type="button" className={boardBtn("ghost")} onClick={() => void withdraw()} disabled={busy !== null}>
                      {busy === "withdraw" ? <Spinner className="text-current" /> : "Withdraw draft"}
                    </button>
                  ) : null}
                  <button type="button" className={boardBtn()} onClick={() => persist("draft")} disabled={busy !== null}>
                    {busy === "draft" ? <Spinner className="text-current" /> : "Save draft"}
                  </button>
                  <button type="button" className={boardBtn("primary")} onClick={() => persist("completed")} disabled={busy !== null}>
                    {busy === "completed" ? <Spinner className="text-current" /> : "Submit review"}
                  </button>
                </div>
              )}
            </div>
          ) : (
            <div className={reviewCard}>
              <GpLeadReview orgSlug={orgSlug} slotId={slotId} form={form} payload={payload} onStatus={setAdminStatus} />
            </div>
          )}
        </div>

        <div className="flex min-w-0 flex-[1_1_300px] flex-col gap-6">
          <MarkingPanel
            marking={marking}
            failedReason={reviews.attempt_failed_reason}
            feedback={feedback}
            busy={busy === "retry"}
            disabled={busy !== null}
            error={retryError}
            onRetry={retryMarking}
            form={form}
          />
          {/* The marking is the machine's reading of the consultation; this is
            the consultation. A marker is asked to agree or disagree with the
            first, which is not a judgement they can make from a score alone. */}
          <AttemptTranscript attemptId={attemptId} cardClassName={reviewCard} />
          <div className={reviewCard}>
            <h2 className="text-base font-semibold leading-normal">What the reviewers agreed</h2>
            <SlotReviewers reviews={reviews} />
          </div>
        </div>
      </div>
    </>
  );
}
