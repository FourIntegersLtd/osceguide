"use client";

import { useCallback, useState } from "react";
import { Alert, AsyncBoundary, Badge, Button, B2CPageHeader, FoldSection, Spinner, Panel, StepGuide } from "@/foundation/ui";
import { errorMessage, useAsync } from "@/foundation/hooks";
import { type AttemptFeedbackRead } from "@/capabilities/feedback";
import type { RatingValue } from "@/capabilities/feedback/rubric";
import { AttemptTranscript } from "@/domains/assess/AttemptTranscript";
import { readMySlotReview, retrySlotMarking, saveReview } from "@/domains/assess/api";
import { readMarking } from "@/domains/assess/readMarking";
import { CandidateStepper } from "@/domains/assess/CandidateStepper";
import { MarkingPanel } from "@/domains/assess/MarkingPanel";
import { can, useSession } from "@/foundation/session";
import { GpLeadReview, SlotReviewers, readSlotReviews } from "@/domains/assess/results";
import { markingState, openForm, slotNextLine, slotReviewSteps } from "@/domains/assess/results/slotReviewSteps";
import type { SlotReviews } from "@/domains/assess/results";
import { ReviewFields } from "@/domains/assess/results/ReviewFields";
import { fieldValuesFor, initialRatings } from "@/domains/assess/results/reviewForm";

/**
 * A station, marked three ways.
 *
 * An observer's own review, the lead's authoritative one, and what everybody
 * who watched agreed — beside the machine's marking. The retiring client had
 * the first of those and the platform had no screen for the other two at all,
 * so a GP lead's review existed on the backend and nothing could write one.
 *
 * The fields to rate are the slot's review form (`SlotReviewsRead.form`),
 * generated by the backend from the station's rubric: every rateable path,
 * the rating kind they take and the domains a submit must cover. So the form
 * is the same for every exam and holds no list of domains or grades here.
 * The backend refuses a submit that leaves a required domain unrated, so that
 * rule is shown, not enforced, in the browser.
 */
/** `attempt_failed_reason` is declared here until the generated types carry it. */
type SlotReviewsRead = SlotReviews & { attempt_failed_reason?: string | null };

export function SlotReview({
  orgSlug,
  slotId,
  attemptId,
  sittingId = null,
}: {
  orgSlug: string;
  slotId: string;
  attemptId: string | null;
  /** The sitting this was opened from, when it was opened from its results. */
  sittingId?: string | null;
}) {
  /*
   * My review is read directly (`GET .../reviews/mine`). An earlier version
   * called that route before it existed, answered 405 on every load and
   * swallowed it, so a reviewer's own draft never came back; a failure here
   * is a failure, not "no review".
   */

  const state = useAsync(
    async (signal) => {
      const [marking, reviews, mine] = await Promise.all([
        // No marking yet (a 404) is an ordinary state beside a review form, and so is a marking
        // this person may not read (a 403). Any other failure is a failure: the boundary shows it.
        readMarking(attemptId, signal),
        readSlotReviews(orgSlug, slotId, signal) as Promise<SlotReviewsRead>,
        readMySlotReview(orgSlug, slotId, signal),
      ]);
      return { feedback: marking.feedback, hidden: marking.hidden, reviews, mine };
    },
    [orgSlug, slotId, attemptId],
  );

  return (
    <div className="flex flex-col gap-6">
      <B2CPageHeader
        title="Mark this station"
        subtitle="The automatic marking, your marks and the admin's review."
        action={sittingId ? <CandidateStepper orgSlug={orgSlug} sittingId={sittingId} slotId={slotId} /> : undefined}
      />
      {state.data?.hidden ? (
        <Alert tone="warning">
          You are not named on this station&apos;s circuit, so its automatic marking is not shown to you.
        </Alert>
      ) : null}
      <AsyncBoundary state={state}>
        {(data) => (
          <Editor
            orgSlug={orgSlug}
            slotId={slotId}
            attemptId={attemptId}
            feedback={data.feedback}
            reviews={data.reviews}
            initial={data.mine}
            onSaved={state.reload}
          />
        )}
      </AsyncBoundary>
    </div>
  );
}

function Editor({
  orgSlug,
  slotId,
  attemptId,
  feedback,
  reviews,
  initial,
  onSaved,
}: {
  orgSlug: string;
  slotId: string;
  attemptId: string | null;
  feedback: AttemptFeedbackRead | null;
  reviews: SlotReviewsRead;
  initial: { field_values: Record<string, unknown>; notes: string | null; status: string } | null;
  onSaved: () => void;
}) {
  const { session } = useSession();
  const isAdmin = can(session, "sign_off_results");
  const open = openForm(isAdmin);
  // The admin's review status is read by its own form; the steps only follow it.
  const [adminStatus, setAdminStatus] = useState<string | null>(null);
  const form = reviews.form ?? null;
  // Results arrive oldest first; the latest marking is the one to agree or disagree with.
  const result = feedback?.results?.at(-1) ?? null;
  const payload = result?.payload ?? null;

  /*
   * Keyed by the form's own paths (`tasks.safety_net.score`). The backend
   * counts only a path that ends in the rubric's rating field, and a bare
   * domain key would write a rating that scores, summaries and completion
   * checks all silently ignore — so the path is never built here.
   */
  const [ratings, setRatings] = useState<Record<string, RatingValue>>(() =>
    initialRatings(form, initial?.field_values),
  );
  const [notes, setNotes] = useState(initial?.notes ?? "");
  const [busy, setBusy] = useState<"draft" | "completed" | "retry" | null>(null);
  const [error, setError] = useState<Error | null>(null);
  const [saved, setSaved] = useState<string | null>(null);
  // Its own message, shown beside the marking it belongs to and not under the marks form too.
  const [retryError, setRetryError] = useState<Error | null>(null);

  const submitted = initial?.status === "completed";
  const marking = markingState({
    attemptId,
    hasResult: result !== null,
    hasRubric: Boolean(feedback?.rubric),
    markingFailed: feedback?.marking_failed === true,
    failedReason: reviews.attempt_failed_reason,
  });
  const retryMarking = useCallback(async () => {
    setBusy("retry");
    setRetryError(null);
    try {
      await retrySlotMarking(orgSlug, slotId);
      onSaved();
    } catch (cause) {
      setRetryError(cause instanceof Error ? cause : new Error(String(cause)));
    } finally {
      setBusy(null);
    }
  }, [orgSlug, slotId, onSaved]);
  const steps = slotReviewSteps({
    marking,
    mine: initial?.status === "completed" ? "completed" : initial ? "draft" : "none",
    admin: !isAdmin ? null : adminStatus === "completed" ? "completed" : adminStatus ? "draft" : "none",
  });

  const persist = useCallback(
    async (status: "draft" | "completed") => {
      setBusy(status);
      setError(null);
      try {
        await saveReview(orgSlug, slotId, { fieldValues: fieldValuesFor(ratings), notes: notes || null, status });
        setSaved(status === "draft" ? "Draft saved" : "Review submitted");
        onSaved();
      } catch (cause) {
        setError(cause instanceof Error ? cause : new Error(String(cause)));
      } finally {
        setBusy(null);
      }
    },
    [orgSlug, slotId, ratings, notes, onSaved],
  );

  const mineReadOnly = submitted || open !== "mine";
  return (
    <>
      <StepGuide steps={steps} current={open} line={slotNextLine(open, steps)} />
      <div className="grid grid-cols-1 gap-5 lg:grid-cols-[minmax(0,2fr)_minmax(0,1fr)]">
        <div className="flex flex-col gap-4">
          <FoldSection
            title="Your marks"
            defaultOpen={open === "mine"}
            description={open === "mine" ? undefined : "Read-only here. An admin writes the review that counts."}
            meta={
              <Badge variant={submitted ? "success" : "neutral"} dot>
                {submitted ? "Submitted" : "Draft"}
              </Badge>
            }
          >
            <div className="flex flex-col gap-4">
              {error && <Alert tone="danger">{errorMessage(error)}</Alert>}
              {saved && !error && <Alert tone="success">{saved}</Alert>}

              <ReviewFields
                form={form}
                ratings={ratings}
                onRate={(path, value) => setRatings((current) => ({ ...current, [path]: value }))}
                payload={payload}
                disabled={mineReadOnly}
              />

              <label className="flex flex-col gap-1.5">
                <span className="text-osce-meta font-medium text-b2b-headline">Notes</span>
                <textarea
                  rows={5}
                  value={notes}
                  disabled={mineReadOnly}
                  onChange={(event) => setNotes(event.target.value)}
                  className="rounded-control border border-b2b-border bg-b2b-surface px-3 py-2 text-osce-body text-b2b-headline disabled:bg-canvas"
                  placeholder="What you saw, in the words you would say to them."
                />
              </label>

              {!mineReadOnly && (
                <div className="flex justify-end gap-2">
                  <Button themeType="b2b" variant="secondary" onClick={() => persist("draft")} disabled={busy !== null}>
                    {busy === "draft" ? <Spinner /> : "Save draft"}
                  </Button>
                  <Button themeType="b2b" variant="commit" onClick={() => persist("completed")} disabled={busy !== null}>
                    {busy === "completed" ? <Spinner /> : "Submit review"}
                  </Button>
                </div>
              )}
            </div>
          </FoldSection>

          {isAdmin ? (
            <FoldSection
              title="Admin's review"
              defaultOpen={open === "admin"}
              description="One overall mark for the station. This is the mark that counts."
            >
              <GpLeadReview orgSlug={orgSlug} slotId={slotId} form={form} payload={payload} onStatus={setAdminStatus} />
            </FoldSection>
          ) : null}

          <Panel title="What the reviewers agreed">
            <SlotReviewers reviews={reviews} />
          </Panel>
        </div>

        <div className="flex flex-col gap-4">
          <MarkingPanel
            marking={marking}
            failedReason={reviews.attempt_failed_reason}
            feedback={feedback}
            busy={busy === "retry"}
            disabled={busy !== null}
            error={retryError}
            onRetry={retryMarking}
          />
          {/* The marking is the machine's reading of the consultation; this is
            the consultation. A marker is asked to agree or disagree with the
            first, which is not a judgement they can make from a score alone. */}
          <AttemptTranscript attemptId={attemptId} />
        </div>
      </div>
    </>
  );
}
